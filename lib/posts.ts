import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

// A post is a folder in content/posts/<slug>/ containing an index.md file (+ its images, csv...)
export const POSTS_DIR = path.join(process.cwd(), 'content/posts');

export type PostFrontmatter = {
  title: string;
  description: string;
  seoDescription: string;
  keywords: string;
  family: string;
  chartType: string;
  slug: string;
  // false when the code of the post can not run in the browser (libraries not available in Pyodide...)
  interactive?: boolean;
};

export type Post = PostFrontmatter & {
  body: string;
  dir: string;
};

export function getAllPostSlugs(): string[] {
  return fs
    .readdirSync(POSTS_DIR)
    .filter((slug) => fs.existsSync(path.join(POSTS_DIR, slug, 'index.md')))
    .sort();
}

export function getPost(slug: string): Post {
  const dir = path.join(POSTS_DIR, slug);
  const file = fs.readFileSync(path.join(dir, 'index.md'), 'utf8');
  const { data, content } = matter(file);
  return { ...(data as PostFrontmatter), slug, body: content, dir };
}

export type PostSummary = Pick<PostFrontmatter, 'slug' | 'title' | 'chartType'> & {
  // Lightweight thumbnail of the first chart of the post (generated by scripts/prepare-assets.ts)
  thumb?: string;
};

let summaries: PostSummary[] | null = null;

// Title, chart type and thumbnail of every post (cached: read once per build)
export function getPostSummaries(): PostSummary[] {
  if (!summaries) {
    summaries = getAllPostSlugs().map((slug) => {
      const { title, chartType } = getPost(slug);
      const hasChart = fs.existsSync(path.join(POSTS_DIR, slug, 'output-1.png'));
      return { slug, title, chartType, thumb: hasChart ? `/posts/${slug}/output-1-thumb.webp` : undefined };
    });
  }
  return summaries;
}

// Other posts about the same chart type. Each post shows the posts that follow it in its section
// (wrapping around), so that every post gets links from its neighbours.
export function getRelatedPosts(slug: string, count = 6): PostSummary[] {
  const all = getPostSummaries();
  const current = all.find((p) => p.slug === slug);
  if (!current) return [];
  const sameType = all.filter((p) => p.chartType === current.chartType && p.thumb);
  const start = sameType.findIndex((p) => p.slug === slug);
  const ordered = [...sameType.slice(start + 1), ...sameType.slice(0, Math.max(start, 0))];
  return ordered.filter((p) => p.slug !== slug && p.slug !== 'basic-template').slice(0, count);
}
